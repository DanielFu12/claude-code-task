# ---------- 元素构造小工具 ----------
def T(s, x, y, size=56, at=0, font="b", color="ink", **k):
    return dict(t="text", s=s, x=x, y=y, size=size, at=at, font=font, color=color, **k)


def E(ch, x, y, size=180, at=0, **k):
    k.setdefault("anim", "pop")
    return dict(t="emoji", ch=ch, x=x, y=y, size=size, at=at, **k)


def R(x, y, w, h, at=0, fill="panel", outline="edge", r=30, **k):
    k.setdefault("anim", "fade")
    return dict(t="rect", x=x, y=y, w=w, h=h, at=at, fill=fill, outline=outline, r=r, **k)


def A(x1, y1, x2, y2, at=0, color="muted", w=6, head=True, **k):
    k.setdefault("anim", "wipe" if abs(y2 - y1) < abs(x2 - x1) else "fade")
    return dict(t="line", x1=x1, y1=y1, x2=x2, y2=y2, at=at, color=color, w=w, head=head, **k)


def L(x1, y1, x2, y2, at=0, color="edge", w=4, **k):
    return A(x1, y1, x2, y2, at=at, color=color, w=w, head=False, **k)


def CHIP(s, x, y, size=42, at=0, color="dark", fill="amber", **k):
    return dict(t="chip", s=s, x=x, y=y, size=size, at=at, color=color, fill=fill, **k)


def HEAD(icon, s, at=0, **k):
    return [E(icon, 150, 110, 76, at=at, **k), T(s, 210, 110, 52, at=at, color="amber", al="l", anim="left", **k)]


def CARD(s, x, y, at=0, emoji=None, **k):
    return dict(t="card", s=s, emoji=emoji, x=x, y=y, w=210, h=290, at=at, **k)


def FRAME(x, y, w, h, at=0, color="green", **k):
    return dict(t="frame", x=x, y=y, w=w, h=h, at=at, color=color, **k)


def STRIKE(x1, x2, y, at=0, **k):
    return dict(t="line", x1=x1, y1=y, x2=x2, y2=y, at=at, color="coral", w=10, head=False, anim="wipe", dur=0.45, **k)


def BAR(x, y, w, h, f0, f1, color, at=0, label=None, **k):
    k.setdefault("anim", "wipe")
    return dict(t="bar", x=x, y=y, w=w, h=h, f0=f0, f1=f1, color=color, at=at, label=label, **k)


