def tts_text(s):
    """配音用文本：去掉只给字幕看的符号。"""
    for a, b in (("「", ""), ("」", ""), ("——", "，"), ("“", ""), ("”", ""),
                 ("福勒", "福乐")):   # 多音字：勒读 lè
        s = s.replace(a, b)
    return s


