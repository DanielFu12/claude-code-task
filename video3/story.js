// 计算时间轴：卡片落在拍点上，段落对齐到小节（4 拍）
export function buildTimeline() {
  const beat = 60 / BPM, bar = beat * 4;
  let t = 0;
  const sections = STORY.map(sec => {
    const start = t;
    let lt = 0;
    const cards = sec.cards.map(c => {
      const plain = c.t.replace(/[\[\]{}|]/g, '');
      let b = c.b;
      if (!b) { const sec_ = plain.length / 5.5 + 1.2; b = Math.max(4, Math.round(sec_ / beat / 2) * 2); }
      const card = { ...c, b, start: lt, dur: b * beat };
      lt += b * beat;
      return card;
    });
    const bars = Math.ceil(lt / bar - 1e-6);
    const dur = bars * bar;
    t += dur;
    return { ...sec, start, dur, bars, cards };
  });
  return { bpm: BPM, beat, bar, total: t, sections };
}
